export type Lang = 'en' | 'es';

export function detectDefaultLang(): Lang {
  try {
    const l = (navigator.language || 'en').toLowerCase();
    return l.startsWith('es') ? 'es' : 'en';
  } catch {
    return 'en';
  }
}

